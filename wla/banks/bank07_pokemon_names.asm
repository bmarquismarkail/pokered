DoClearSaveDialogue:
	call ClearScreen
	call RunDefaultPaletteCommand
	call LoadFontTilePatterns
	call LoadTextBoxTilePatterns
	ld hl, ClearSaveDataText
	call PrintText
	ld hl, wTileMap + (7 * 20) + 14
	ld bc, ((8) << 8) | (15)
	ld a, NO_YES_MENU
	ld (wTwoOptionMenuID), a
	ld a, TWO_OPTION_MENU
	ld (wTextBoxID), a
	call DisplayTextBoxID
	ld a, (wCurrentMenuItem)
	and a
	jp z, Init
	ld b, $1c
	ld hl, $7b6a
	call Bankswitch
	jp Init

ClearSaveDataText:
	.DB $17
	.DW $5d96
	.DB $22
	.DB $50
DisplayElevatorFloorMenu:
	ld hl, WhichFloorText
	call PrintText
	ld hl, wItemList
	ld a, l
	ld (wListPointer), a
	ld a, h
	ld (wListPointer + 1), a
	ld a, (wListScrollOffset)
	push af
	xor a
	ld (wCurrentMenuItem), a
	ld (wListScrollOffset), a
	ld (wPrintItemPrices), a
	ld a, SPECIALLISTMENU
	ld (wListMenuID), a
	call DisplayListMenuID
	pop bc
	ld a, b
	ld (wListScrollOffset), a
	ret c
	ld hl, wCurrentMapScriptFlags
	set BIT_CUR_MAP_USED_ELEVATOR, (hl)
	ld hl, wElevatorWarpMaps
	ld a, (wWhichPokemon)
	add a
	ld d, 0
	ld e, a
	add hl, de
	ld a, (HL+)
	ld b, a
	ld a, (hl)
	ld c, a
	ld hl, wWarpEntries
	call DisplayElevatorFloorMenu.UpdateWarp

DisplayElevatorFloorMenu.UpdateWarp:
	inc hl
	inc hl
	ld a, b
	ld (HL+), a ; destination warp ID
	ld a, c
	ld (HL+), a ; destination map ID
	ret

WhichFloorText:
	.DB $17
	.DW $5dad
	.DB $22
	.DB $50
